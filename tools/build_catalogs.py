"""Generate catalogs/*.md from the pack manifests. The manifests are the only source of truth;
never edit the catalogs by hand. Usage: python tools/build_catalogs.py"""
import json, glob, os
from collections import defaultdict
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
voc = json.load(open(os.path.join(root, "vocabularies/vocabularies.json")))
fps = {p["id"]: p["name"] for p in json.load(open(os.path.join(root, "patterns/failure-patterns.json")))["patterns"]}
packs = []
for path in sorted(glob.glob(os.path.join(root, "library/*/*/manifest.json"))):
    m = json.load(open(path)); m["_dir"] = os.path.relpath(os.path.dirname(path), root).replace(os.sep, "/"); packs.append(m)
def link(m, base="../"): return f"[{m['id']}]({base}{m['_dir']}/) {m['title']}"
def write(name, title, intro, groups, labels=None):
    with open(os.path.join(root, "catalogs", name), "w", encoding="utf-8") as f:
        f.write(f"# {title}\n\n_Generated by tools/build_catalogs.py from the pack manifests. Do not edit by hand._\n\n{intro}\n\n")
        for key in groups:
            items = groups[key]
            if not items: continue
            f.write(f"## {labels.get(key, key) if labels else key}\n\n| Pack | Level | Work class | Status |\n|---|---|---|---|\n")
            for m in sorted(items, key=lambda x: x["id"]):
                f.write(f"| {link(m)} | {m['level']} | {m['work_class']} | {m['status']} |\n")
            f.write("\n")
os.makedirs(os.path.join(root, "catalogs"), exist_ok=True)
def facet(name, order):
    g = defaultdict(list)
    for m in packs:
        for v in m.get(name, []): g[v].append(m)
    return {k: g[k] for k in order if k in g}
write("by-workflow.md", "Packs by workflow", "Primary entry for Revit users and developers: what area of Revit the work touches. A pack appears under every workflow it involves; its folder is the first one.", facet("workflows", list(voc["workflows"])), {k: f"{k}: {v}" for k, v in voc["workflows"].items()})
write("by-discipline.md", "Packs by discipline", "Entry for engineers and designers. 'generic' packs apply to every discipline.", facet("disciplines", voc["disciplines"]))
write("by-project-type.md", "Packs by project type", "Entry by building type. Project-level workflows are listed in project-workflows/.", facet("project_types", voc["project_types"]))
write("by-phase.md", "Packs by project phase", "", facet("phases", voc["phases"]))
write("by-role.md", "Packs by role", "", facet("roles", voc["roles"]))
g = defaultdict(list)
for m in packs: g[m["work_class"]].append(m)
write("by-work-class.md", "Packs by work class", "Work class = what drives the result; it decides the preview and the proof of 'done'. See docs/model.md.", {k: g[k] for k in voc["work_classes"] if k in g}, {k: f"{k}: {v}" for k, v in voc["work_classes"].items()})
write("by-failure-pattern.md", "Packs by failure pattern", "Learn from what went wrong: each pack is listed under the failure patterns it records.", facet("failure_patterns", list(fps)), {k: f"{k}: {v}" for k, v in fps.items()})
g = defaultdict(list)
for m in packs:
    for v in m["revit_versions_tested"]: g[v].append(m)
write("by-revit-version.md", "Packs by Revit version tested", "Only versions in which the pack actually ran.", dict(sorted(g.items())))
g = defaultdict(list)
for m in packs: g[str(m["level"])].append(m)
write("by-level.md", "Packs by level", "", {k: g[k] for k in sorted(g)}, {k: f"Level {k}: {v}" for k, v in voc["levels"].items()})
# Machine-readable index for AI agents (see AGENTS.md)
pws = []
for path in sorted(glob.glob(os.path.join(root, "project-workflows/*/manifest.json"))):
    w = json.load(open(path)); pws.append({"id": w["id"], "revision": w.get("revision", 1), "title": w["title"], "level": w["level"], "context": w["context"], "intent": w["intent"],
        "steps": [{"step": s["step"], "work_class": s["work_class"], "do": s["do"], "packs": s["packs"]} for s in w["sequence"]],
        "path": os.path.relpath(os.path.dirname(path), root).replace(os.sep, "/"), "status": w["status"]})
index = {"name": "ARPL index", "description": "Machine-readable index of ARPL instruction packs. Generated by tools/build_catalogs.py; read AGENTS.md for how to use it.",
    "raw_base": "https://raw.githubusercontent.com/gschmidtke/ARPL/main/",
    "vocabulary_version": voc["version"],
    "provenance": "Record every pack you used as {arpl_pack, pack_revision, revit_version, result}. To pin exact content, replace main in raw_base with a commit SHA or release tag.",
    "lookup_order": ["project_workflows", "packs (level 3, then 2, then 1)", "failure_patterns"],
    "read_order_per_pack": ["final/rule.json", "manifest.json", "vNN/ iterations (failures)", "failure_patterns listed in the manifest"],
    "work_classes": voc["work_classes"], "project_workflows": pws, "packs": [], "failure_patterns": json.load(open(os.path.join(root, "patterns/failure-patterns.json")))["patterns"]}
for m in packs:
    rule = json.load(open(os.path.join(root, m["_dir"], "final/rule.json")))
    index["packs"].append({k: m.get(k) for k in ["id", "revision", "title", "use_when", "not_for", "api_terms", "level", "work_class", "workflows", "disciplines", "project_types", "phases", "revit_versions_tested", "failure_patterns", "status", "domain_overlays"] if m.get(k) is not None}
        | {"rule": rule.get("rule"), "validation": rule.get("validation"), "path": m["_dir"]})
json.dump(index, open(os.path.join(root, "index.json"), "w", encoding="utf-8"), indent=2, ensure_ascii=False)
print(f"{len(packs)} packs -> catalogs and index.json written")
